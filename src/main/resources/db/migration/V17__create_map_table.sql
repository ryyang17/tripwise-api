-- Create map table to store map data from external APIs (Google Maps, Mapbox, etc.)
CREATE TABLE IF NOT EXISTS map (
    map_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    trip_id BIGINT,
    provider VARCHAR(100),
    waypoints TEXT,
    distance VARCHAR(50),
    duration VARCHAR(50),
    location VARCHAR(255),
    raw_payload TEXT,
    created_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (user_id) REFERENCES app_user(user_id) ON DELETE CASCADE
);

-- Create index on trip_id for faster queries
CREATE INDEX idx_map_trip_id ON map(trip_id);

-- Create index on user_id for faster queries
CREATE INDEX idx_map_user_id ON map(user_id);

